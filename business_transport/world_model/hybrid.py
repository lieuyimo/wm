"""RHWM-v1: full observable system-state forecasts from an existing event model.

V4 learns eligible station service-completion probabilities; all motion,
resource admission and workflow successor updates are the existing public
legal transition model. This is a HYBRID world model; no other dynamics are
claimed to be learned. No private simulator state or future exogenous events
enter the prediction API.
"""
from __future__ import annotations

from collections import Counter, defaultdict
import hashlib
from typing import Callable, Sequence

from business_transport.dynamics import WorkflowDynamics
from business_transport.session_dynamics import SessionRuleDynamics
from business_transport.workflow_transition import check_business_transition
from lab_transport.state_v2 import ObservationV2
from lab_transport.torch_structured_adapter import ProgressAwareRule
from lab_transport.transition_schema import Assignment

from .contracts import (
    EventForecast, ForecastBatch, ForecastParticle, ForecastStep,
    StepDistribution,
)


Continuation = Callable[[ObservationV2], Sequence[Assignment]]


def _seed(master: int, particle: int, tick: int) -> int:
    # No process-specific Python hash() and no true simulator RNG sharing.
    blob = f"rhwm-v1|{master}|{particle}|{tick}".encode("utf-8")
    return int.from_bytes(hashlib.sha256(blob).digest()[:8], "big")


def _distribution(particles: tuple[ForecastParticle, ...], step: int) -> StepDistribution:
    states = [p.steps[step].next_state for p in particles]
    n = len(states)
    if n == 0:
        raise ValueError("cannot summarize zero particles")
    sample_ids = set().union(*(set(s.id for s in st.samples) for st in states))
    robot_ids = {r.id for r in states[0].robots}
    station_ids = {s.id for s in states[0].stations}
    if any({r.id for r in st.robots} != robot_ids or
           {s.id for s in st.stations} != station_ids for st in states):
        raise AssertionError("robot/station IDs changed across forecast particles")
    samples = {}
    for sid in sorted(sample_ids):
        counts = Counter(next((s.status for s in st.samples if s.id == sid),
                              "not_yet_observed") for st in states)
        samples[sid] = {k: v / n for k, v in sorted(counts.items())}
    tasks = {}
    for rid in sorted(robot_ids):
        counts = Counter(next(r.task_id if r.task_id is not None else "idle"
                              for r in st.robots if r.id == rid) for st in states)
        tasks[rid] = {k: v / n for k, v in sorted(counts.items())}
    busy = {}
    for sid in sorted(station_ids):
        busy[sid] = sum(bool(next(s.service_in_progress
                                  for s in st.stations if s.id == sid))
                        for st in states) / n
    occupancy = defaultdict(list)
    for st in states:
        per_resource = {}
        for station in st.stations:
            rid = getattr(station, "resource_id", "")
            if not rid:
                raise ValueError("resource identity missing from business world state")
            count = station.resource_occupied
            if rid in per_resource and per_resource[rid] != count:
                raise AssertionError("inconsistent occupancy for stations in same resource")
            per_resource[rid] = count
        for rid, count in per_resource.items():
            occupancy[rid].append(count)
    result = {rid: sum(vals) / n for rid, vals in sorted(occupancy.items())}
    return StepDistribution(
        tick=states[0].tick,
        sample_status_probabilities=samples,
        robot_task_probabilities=tasks,
        station_service_probability=busy,
        resource_occupancy_mean=result,
        expected_waiting_samples=sum(sum(s.status == "waiting" for s in st.samples)
                                     for st in states) / n,
        expected_completed_samples=sum(sum(s.status == "completed" for s in st.samples)
                                       for st in states) / n,
        expected_in_transit_samples=sum(sum(s.status == "in_transit" for s in st.samples)
                                        for st in states) / n,
    )


class HybridSystemWorldModel:
    """An action-conditioned, observable, lawful state transition distribution.

    First action comes from the caller; all later actions must be generated by
    an explicit continuation policy using only the latest predicted public
    state. Unknown future faults, jobs and conditional retests are NOT
    generated by this model. Loading research-only V4 requires explicit
    experimental=True (never an implicit deployment permission).
    """

    MAX_HORIZON = 20
    MAX_PARTICLES = 8

    def __init__(self, geometry, rules, *, kind="rule", checkpoint=None,
                 experimental=False, service_baseline=None):
        if kind not in ("rule", "v4", "kaplan_meier"):
            raise ValueError("unsupported RHWM world-model probability source")
        if kind == "v4":
            if checkpoint is None or not experimental:
                raise ValueError("V4 requires frozen checkpoint and explicit research opt-in")
            core = SessionRuleDynamics(
                geometry, rules, checkpoint, feature_version="v4",
                experimental=True)
        elif kind == "kaplan_meier":
            if checkpoint is not None or service_baseline is None:
                raise ValueError("Kaplan-Meier requires fitted library baseline, not a V4 checkpoint")
            from .kaplan_meier import KaplanMeierRuleDynamics
            core = KaplanMeierRuleDynamics(geometry, rules, service_baseline)
        else:
            if checkpoint is not None or service_baseline is not None:
                raise ValueError("rule-only world model cannot load fitted service models")
            core = ProgressAwareRule(geometry)
        self.geometry = geometry
        self.rules = rules
        self.kind = kind
        self.model_version = {"v4":"rhwm-v1-hybrid-v4",
                              "rule":"rhwm-v1-rule",
                              "kaplan_meier":"rhwm-v1-km-reference"}[kind]
        self.transition = WorkflowDynamics(core, rules)

    def predict_next(self, public_state: ObservationV2,
                     legal_assignments: Sequence[Assignment], *,
                     sampling_seed: int = 1810) -> ForecastStep:
        if not isinstance(public_state, ObservationV2):
            raise ValueError("world model requires a derived public ObservationV2")
        if type(sampling_seed) is not int:
            raise ValueError("sampling_seed must be an integer")
        action = tuple(legal_assignments)
        self.transition.reset_seed(sampling_seed)
        predicted = self.transition.predict_next(public_state, action)
        check_business_transition(public_state, predicted, self.geometry, self.rules, action)
        if predicted.tick != public_state.tick + 1:
            raise AssertionError("world model did not advance exactly one tick")
        evidence = ()
        if self.kind in ("v4", "kaplan_meier"):
            # This trace is computed by the actual model inference call on the
            # capacity-prepared observation, not by an extra inconsistent pass.
            evidence = tuple(EventForecast(
                robot_id=e["query"]["robot_id"],
                sample_id=e["query"]["sample_id"],
                phase=e["query"]["phase"],
                station_id=e["query"]["station_id"],
                p_finish_next=e["p_finish"],
                sampled_finished=e["sampled_finished"],
            ) for e in self.transition.model.last_service_events)
        return ForecastStep(public_state, action, predicted,
                            evidence, self.model_version)

    def rollout(self, public_state: ObservationV2,
                first_action: Sequence[Assignment], *,
                continuation_policy: Continuation,
                horizon_ticks: int = 5, particles: int = 3,
                sampling_seed: int = 1810,
                continuation_policy_name: str = "fixed_public_policy") -> ForecastBatch:
        if not callable(continuation_policy):
            raise ValueError("future continuation policy must be callable")
        if (type(horizon_ticks) is not int or
                not 1 <= horizon_ticks <= self.MAX_HORIZON):
            raise ValueError("bounded horizon must be in [1,20]")
        if (type(particles) is not int or
                not 1 <= particles <= self.MAX_PARTICLES):
            raise ValueError("bounded particles must be in [1,8]")
        if type(sampling_seed) is not int:
            raise ValueError("sampling_seed must be an integer")
        if not continuation_policy_name or not isinstance(continuation_policy_name, str):
            raise ValueError("future continuation policy must be named")
        if not isinstance(public_state, ObservationV2):
            raise ValueError("world model requires derived public state")
        first_action = tuple(first_action)
        forecasts = []
        for particle in range(particles):
            state = public_state
            trace = []
            for tick_index in range(horizon_ticks):
                # Future actions are recomputed on the *predicted* state.
                # Never replay a true-world future action sequence as model input.
                action = first_action if tick_index == 0 else tuple(continuation_policy(state))
                step = self.predict_next(
                    state, action,
                    sampling_seed=_seed(sampling_seed, particle, state.tick))
                trace.append(step)
                state = step.next_state
            forecasts.append(ForecastParticle(particle, tuple(trace)))
        result = tuple(forecasts)
        summaries = tuple(_distribution(result, i) for i in range(horizon_ticks))
        return ForecastBatch(
            self.model_version, public_state, first_action,
            continuation_policy_name, result, summaries)
